    {
      FileReader reader = new FileReader();
      Spectrum spec = reader.ReadSpectrum(dataFilePathMzXML, 1);

      Assert.AreEqual(1, spec.ScanNumber);
      Assert.AreEqual(1, spec.MsLevel);
      Assert.AreEqual(0.50, spec.RetentionTime, 1e-6);
      Assert.AreEqual(4500.0, spec.TotalIonCurrent, 1e-9);
      Assert.AreEqual(3, spec.Count);
      Assert.AreEqual(400.1, spec.DataPoints[0].Mz, 1e-9);
      Assert.AreEqual(1000.0, spec.DataPoints[0].Intensity, 1e-9);
      Assert.AreEqual(450.2, spec.DataPoints[1].Mz, 1e-9);
      Assert.AreEqual(2000.0, spec.DataPoints[1].Intensity, 1e-9);
      Assert.AreEqual(500.3, spec.DataPoints[2].Mz, 1e-9);
      Assert.AreEqual(1500.0, spec.DataPoints[2].Intensity, 1e-9);
