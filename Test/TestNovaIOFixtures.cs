    [TestMethod]
    public void MzXML_Ms2Spectrum_PrecursorFields()
    {
      FileReader reader = new FileReader();
      Spectrum spec = reader.ReadSpectrum(dataFilePathMzXML, 2);

      Assert.AreEqual(2, spec.ScanNumber);
      Assert.AreEqual(2, spec.MsLevel);
